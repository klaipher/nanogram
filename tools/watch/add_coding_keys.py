#!/usr/bin/env python3
"""Adds explicit snake_case CodingKeys to every generated TDShim model struct.

TDLib's JSON uses snake_case keys. The models used to rely on
`keyDecodingStrategy = .convertFromSnakeCase`, which converts every key of every object on every
decode and was 50-74% of each decode. With explicit keys the decoder compares raw strings.

Each raw value is Foundation's convertToSnakeCase of the property name, and the script checks that
Foundation's convertFromSnakeCase maps it back to the same name, so the wire keys stay exactly the
ones the strategy accepted. `WatchAppTests/TDModelCodingKeysTests` proves it at run time for every
model. Idempotent: a struct's existing generated CodingKeys block is replaced.

Run after regenerating the models (see Packages/TDShim/Sources/TDShim/Generated/README.md):

    python3 tools/watch/add_coding_keys.py
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                    "Telegram", "WatchApp", "Packages", "TDShim", "Sources", "TDShim", "Generated", "Models")

STRUCT_RE = re.compile(r"^public struct (\w+): Codable\b.*\{$")
PROP_RE = re.compile(r"^    public (?:let|var) (`?\w+`?): ")
BEGIN = "    // Generated by tools/watch/add_coding_keys.py: TDLib's snake_case keys."


def to_snake(name):
    """Foundation's JSONEncoder.KeyEncodingStrategy._convertToSnakeCase."""
    if not name:
        return name
    words = []
    word_start = 0
    i = 0
    n = len(name)
    search = 1
    while search < n:
        # find next uppercase
        j = search
        while j < n and not name[j].isupper():
            j += 1
        if j >= n:
            break
        upper_start = j
        words.append((word_start, upper_start))
        # find next lowercase after upper_start
        k = upper_start
        while k < n and not name[k].islower():
            k += 1
        if k >= n:
            word_start = upper_start
            search = n
            break
        if k - upper_start == 1:
            word_start = upper_start
        else:
            # a run of capitals: the last capital starts the next word
            words.append((upper_start, k - 1))
            word_start = k - 1
        search = k
    words.append((word_start, n))
    return "_".join(name[a:b].lower() for a, b in words if b > a)


def from_snake(key):
    """Foundation's JSONDecoder.KeyDecodingStrategy._convertFromSnakeCase (no edge underscores)."""
    parts = [p for p in key.split("_") if p]
    if len(parts) <= 1:
        return key
    return parts[0].lower() + "".join(p[:1].upper() + p[1:].lower() for p in parts[1:])


def process(path):
    with open(path) as f:
        lines = f.read().split("\n")
    out = []
    i = 0
    changed = False
    while i < len(lines):
        line = lines[i]
        m = STRUCT_RE.match(line)
        if not m:
            out.append(line)
            i += 1
            continue
        out.append(line)
        i += 1
        props = []
        body = []
        while lines[i] != "}":
            body.append(lines[i])
            pm = PROP_RE.match(lines[i])
            if pm:
                props.append(pm.group(1))
            i += 1
        # drop an earlier generated block
        if BEGIN in body:
            s = body.index(BEGIN)
            e = s
            while body[e] != "    }":
                e += 1
            del body[s:e + 2]  # block and the blank line after it
            changed = True
        if props:
            block = [BEGIN, "    private enum CodingKeys: String, CodingKey {"]
            for p in props:
                bare = p.strip("`")
                raw = to_snake(bare)
                if from_snake(raw) != bare:
                    sys.exit(f"{path}: {m.group(1)}.{bare}: snake key {raw!r} does not map back")
                block.append(f"        case {p}" if raw == bare else f"        case {p} = \"{raw}\"")
            block += ["    }", ""]
            # insert before `public init(` (or at the end of the body)
            at = next((k for k, b in enumerate(body) if b.startswith("    public init(")), len(body))
            body[at:at] = block
            changed = True
        out.extend(body)
        out.append(lines[i])  # closing brace
        i += 1
    if changed:
        with open(path, "w") as f:
            f.write("\n".join(out))
    return changed


TEST_LIST = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                         "Telegram", "WatchApp", "Tests", "WatchAppTests", "TDModelList.swift")
ENUM_RE = re.compile(r"^public (?:indirect )?enum (\w+): Codable\b")
KIND_RE = re.compile(r"^    private enum Kind: String, Codable \{$")


def write_test_list():
    """Lists every model for TDModelCodingKeysTests: the structs, and one @type per enum."""
    structs, kinds = [], []
    for name in sorted(os.listdir(ROOT)):
        if not name.endswith(".swift"):
            continue
        with open(os.path.join(ROOT, name)) as f:
            lines = f.read().split("\n")
        enum = None
        for i, line in enumerate(lines):
            m = STRUCT_RE.match(line)
            if m:
                structs.append(m.group(1))
            m = ENUM_RE.match(line)
            if m:
                enum = m.group(1)
            if enum and KIND_RE.match(line):
                first = lines[i + 1].strip()
                assert first.startswith("case "), (name, first)
                kinds.append((enum, first[5:]))
                enum = None
    out = ["// Generated by tools/watch/add_coding_keys.py. Do not edit.",
           "",
           "@preconcurrency import TDShim",
           "",
           "/// Every generated TDShim model struct.",
           "var tdModelStructs: [any (Codable & Equatable).Type] { ["]
    out += [f"    {s}.self," for s in structs]
    out += ["] }", "", "/// The first `@type` of every generated TDShim enum, keyed by type name.",
            "let tdModelEnumSampleType: [String: String] = ["]
    out += [f"    \"{e}\": \"{k}\"," for e, k in kinds]
    out += ["]", ""]
    with open(TEST_LIST, "w") as f:
        f.write("\n".join(out))
    print(f"listed {len(structs)} structs, {len(kinds)} enums")


def main():
    assert to_snake("streetLine1") == "street_line1"
    assert to_snake("sha256Hash") == "sha256_hash"
    assert to_snake("isURLValid") == "is_url_valid"
    assert to_snake("chatId") == "chat_id"
    count = 0
    if "--list-only" in sys.argv:
        write_test_list()
        return
    for name in sorted(os.listdir(ROOT)):
        if name.endswith(".swift") and process(os.path.join(ROOT, name)):
            count += 1
    print(f"updated {count} files")
    write_test_list()


if __name__ == "__main__":
    main()
